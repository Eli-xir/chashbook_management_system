CREATE TABLE attachments (
    attachment_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    attachment_type_id integer NOT NULL,
    extension_id integer NOT NULL,
    attachment_url text NOT NULL,
    original_name text NOT NULL,
    content_type text NOT NULL,
    uploaded_by uuid NOT NULL REFERENCES users,
    is_submitted boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY(extension_id, attachment_type_id) REFERENCES allowed_extensions(extension_id, attachment_type_id)
);
