CREATE TABLE users (
    user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_name varchar(48) NOT NULL CHECK (length(trim(user_name)) > 0),
    password_hash text NOT NULL,
    user_role_id integer NOT NULL REFERENCES user_roles,
    is_active boolean NOT NULL DEFAULT true,
    last_activated_at timestamptz NOT NULL DEFAULT now(),
    last_deactivated_at timestamptz
);
CREATE UNIQUE INDEX unique_active_username ON users(user_name) WHERE is_active;
CREATE TABLE contacts (
    contact_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    contact_no varchar(24) NOT NULL,
    user_id uuid NOT NULL REFERENCES users ON DELETE CASCADE
);
CREATE TABLE sessions (
    session_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users ON DELETE CASCADE,
    expiry_date timestamptz NOT NULL DEFAULT now() + interval '7 days',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE attachment_types (attachment_type_id integer PRIMARY KEY, attachment_type_name text UNIQUE NOT NULL);
