CREATE TABLE heads (
    head_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    parent_head_id integer REFERENCES heads,
    attachment_id integer REFERENCES attachments,
    head_name varchar(160) NOT NULL CHECK (length(trim(head_name)) > 0),
    head_description text,
    is_active boolean NOT NULL DEFAULT true,
    is_transactionable boolean NOT NULL DEFAULT false,
    is_deleted boolean NOT NULL DEFAULT false,
    CHECK (head_id <> parent_head_id)
);
-- Tombstones keep permission IDs and historical versions unchanged after deletion/merge.
CREATE UNIQUE INDEX unique_live_head_name ON heads(head_name) WHERE NOT is_deleted;
CREATE TABLE user_head_permissions (
    head_id integer NOT NULL REFERENCES heads,
    user_id uuid NOT NULL REFERENCES users ON DELETE CASCADE,
    PRIMARY KEY (head_id, user_id)
);
CREATE TABLE transactions (
    transaction_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    head_id integer NOT NULL REFERENCES heads,
    category_group_id integer NOT NULL REFERENCES category_groups,
    user_id uuid NOT NULL REFERENCES users,
    created_by_user_id uuid NOT NULL REFERENCES users,
    current_version_id integer NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE transaction_versions (
    version_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id integer NOT NULL REFERENCES transactions ON DELETE CASCADE,
    transaction_amount numeric(18,2) NOT NULL CHECK (transaction_amount >= 0),
    transaction_type_id integer NOT NULL REFERENCES transaction_types,
    created_at timestamptz NOT NULL DEFAULT now(),
    editor_id uuid NOT NULL REFERENCES users,
    action text NOT NULL,
    head_id integer NOT NULL REFERENCES heads,
    category_group_id integer NOT NULL REFERENCES category_groups,
    is_active boolean NOT NULL,
    head_path text NOT NULL,
    category_name text NOT NULL,
    UNIQUE(transaction_id, version_id)
);
